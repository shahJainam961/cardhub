// Writes apps/web/.env.local and apps/server/.env.local for the local Supabase stack.
// Run after `pnpm db:start`. The file is git-ignored.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const output = execFileSync("pnpm", ["exec", "supabase", "status", "-o", "env"], {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});
const values = Object.fromEntries(
  output
    .split("\n")
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2]]),
);
const url = values.API_URL;
const key = values.PUBLISHABLE_KEY ?? values.ANON_KEY;
if (!url || !key) {
  console.error("Could not read API_URL / PUBLISHABLE_KEY from `supabase status`. Is it running?");
  process.exit(1);
}
const header = "# Local Supabase stack (generated by scripts/write-local-env.mjs)\n";
writeFileSync(
  new URL("../apps/web/.env.local", import.meta.url),
  `${header}VITE_SUPABASE_URL=${url}\nVITE_SUPABASE_PUBLISHABLE_KEY=${key}\nVITE_GAME_SERVER_URL=http://localhost:2567\n`,
);
writeFileSync(
  new URL("../apps/server/.env.local", import.meta.url),
  `${header}SUPABASE_URL=${url}\nSUPABASE_PUBLISHABLE_KEY=${key}\n`,
);
console.log(`Wrote apps/web/.env.local and apps/server/.env.local for ${url}`);
